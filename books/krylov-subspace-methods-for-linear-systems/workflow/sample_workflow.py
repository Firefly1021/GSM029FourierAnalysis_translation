BLOCK = re.compile(r"^% block: ([\w-]+) pages?:([\d,]+) type:([\w-]+)\n", re.M)
MATH = re.compile(r"\\begin\{equation\}(.*?)\\end\{equation\}|\\\[(.*?)\\\]|(?<!\\)\$(.*?)(?<!\\)\$", re.S)


def blocks(text):
    markers = list(BLOCK.finditer(text))
    return [(m.group(1), list(map(int, m.group(2).split(","))), m.group(3),
             text[m.end():markers[i+1].start() if i+1 < len(markers) else len(text)].strip())
            for i, m in enumerate(markers)]


def math_records(text):
    result = []
    for match in MATH.finditer(text):
        latex = next(x for x in match.groups() if x is not None)
        canonical = re.sub(r"\\label\{[^}]+\}", "", latex)
        canonical = re.sub(r"\s+", "", canonical)
        result.append((latex, canonical, "inline" if match.group(3) is not None else "display"))
    return result


