    reader = PdfReader(source)
    labels = reader.page_labels
    outlines = []

    def walk(items, depth=0):
        for item in items:
            if isinstance(item, list):
                walk(item, depth + 1)
            else:
                page = reader.get_destination_page_number(item) + 1
                outlines.append({"title_raw": item.title, "depth": depth,
                                 "pdf_page": page, "printed_page": labels[page-1]})

    walk(reader.outline)
    dump("structured/source/book-outline.json", outlines)
